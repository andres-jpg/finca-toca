-- 2. Funciones -----------------------------------------------------------------
-- Van antes que las tablas porque `tenant_actual()` es DEFAULT de `tenant_id`.
-- Su cuerpo SQL referencia `public.roles` (creada después): por eso
-- `check_function_bodies = false` arriba.

CREATE OR REPLACE FUNCTION public.tenant_actual()
 RETURNS uuid
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  SELECT tenant_id FROM public.roles WHERE user_id = (SELECT auth.uid())
$function$;

CREATE OR REPLACE FUNCTION public.rol_actual()
 RETURNS rol
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  SELECT rol FROM public.roles WHERE user_id = (SELECT auth.uid())
$function$;

CREATE OR REPLACE FUNCTION public.get_cooperativa_users()
 RETURNS TABLE(user_id uuid, email text, rol text, itinerario_id integer, itinerario_nombre text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth'
AS $function$
begin
  return query
  select r.user_id, u.email::text, r.rol::text, ui.itinerario_id, it.nombre::text
  from public.roles r
  join auth.users u on u.id = r.user_id
  left join public.user_itinerarios ui on ui.user_id = r.user_id
  left join public.itinerarios it on it.id = ui.itinerario_id
  where r.rol in ('cooperativa_user', 'cooperativa_admin')
  order by r.rol, u.email;
end;
$function$;

