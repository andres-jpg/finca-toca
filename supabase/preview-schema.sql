-- =============================================
-- 1. TIPOS ENUM
-- =============================================

CREATE TYPE public.vaca_origen AS ENUM ('finca', 'externa');
CREATE TYPE public.vaca_estado AS ENUM ('produccion', 'secado', 'pre_jardin', 'jardin', 'transicion');


-- =============================================
-- 2. TABLAS
-- =============================================

-- Catálogos de gastos
CREATE TABLE public.conceptos_gasto (
  id   smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL UNIQUE
);

CREATE TABLE public.subconceptos_gasto (
  id          smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  concepto_id smallint NOT NULL REFERENCES public.conceptos_gasto(id),
  nombre      text     NOT NULL,
  UNIQUE (concepto_id, nombre)
);

-- Catálogos de ingresos
CREATE TABLE public.conceptos_ingreso (
  id     smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nombre text     NOT NULL UNIQUE
);

CREATE TABLE public.subconceptos_ingreso (
  id          smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  concepto_id smallint NOT NULL REFERENCES public.conceptos_ingreso(id),
  nombre      text     NOT NULL,
  UNIQUE (concepto_id, nombre)
);

-- Toros (sin FK a vacas todavía — dependencia circular)
CREATE TABLE public.toros (
  id               uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at       timestamptz  DEFAULT now(),
  toro_id          integer      NOT NULL,
  nombre           varchar      NOT NULL,
  origen           public.vaca_origen,
  estado           text         CHECK (estado = ANY (ARRAY['jardin'::text, 'reproductor'::text])),
  fecha_compra     date,
  fecha_nacimiento date,
  numero_registro  text,
  madre_id         uuid,                              -- FK a vacas añadida más abajo
  padre_id         uuid         REFERENCES public.toros(id),
  alta             boolean      NOT NULL DEFAULT true
);

-- Vacas (sin FK a toros todavía — dependencia circular)
CREATE TABLE public.vacas (
  id                  uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at          timestamptz  DEFAULT now(),
  vaca_id             integer      NOT NULL UNIQUE,
  nombre              varchar      NOT NULL,
  origen              public.vaca_origen,
  estado              public.vaca_estado,
  fecha_compra        date,
  fecha_nacimiento    date,
  numero_registro     text,
  madre_id            uuid         REFERENCES public.vacas(id),
  padre_id            uuid,                           -- FK a toros añadida más abajo
  padre_pajilla_nombre text,
  alta                boolean      NOT NULL DEFAULT true
);

-- Resolver la dependencia circular toros ↔ vacas
ALTER TABLE public.toros
  ADD CONSTRAINT toros_madre_id_fkey FOREIGN KEY (madre_id) REFERENCES public.vacas(id);
ALTER TABLE public.vacas
  ADD CONSTRAINT vacas_padre_id_fkey FOREIGN KEY (padre_id) REFERENCES public.toros(id);

-- Gastos
CREATE TABLE public.gastos (
  id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at     timestamptz NOT NULL DEFAULT now(),
  fecha          date        NOT NULL,
  valor          bigint      NOT NULL,
  subconcepto_id smallint    REFERENCES public.subconceptos_gasto(id),
  proveedor      text,
  numero_factura text,
  observaciones  varchar,
  pagado         boolean     NOT NULL DEFAULT false
);

-- Pagos (1-a-1 con gastos)
CREATE TABLE public.pagos (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  gasto_id     bigint NOT NULL UNIQUE REFERENCES public.gastos(id),
  forma_pago   text   NOT NULL CHECK (forma_pago = ANY (ARRAY['efectivo'::text, 'transferencia'::text])),
  tipo_cuenta  text,
  banco        text,
  numero_cuenta text
);

-- Ingresos
CREATE TABLE public.ingresos (
  id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at     timestamptz NOT NULL DEFAULT now(),
  fecha          date        NOT NULL,
  valor          bigint      NOT NULL,
  subconcepto_id smallint    NOT NULL REFERENCES public.subconceptos_ingreso(id),
  observaciones  varchar,
  source         text
);

-- Extracciones de leche
CREATE TABLE public.extracciones_leche (
  id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at          timestamptz NOT NULL DEFAULT now(),
  fecha               date        NOT NULL,
  litros              real        NOT NULL,
  vacas_en_produccion integer
);

-- Precios
CREATE TABLE public.precios (
  id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now(),
  valor      integer     NOT NULL,
  tipo       text        NOT NULL DEFAULT 'leche'
);

-- Inventario de pajillas (semen)
CREATE TABLE public.pajillas (
  id                 uuid    PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at         timestamptz NOT NULL DEFAULT now(),
  toro_nombre        text    NOT NULL,
  toro_ref_id        text    NOT NULL,
  fecha_compra       date    NOT NULL,
  cantidad           integer NOT NULL CHECK (cantidad > 0),
  cantidad_disponible integer NOT NULL CHECK (cantidad_disponible >= 0),
  observaciones      text
);

-- Eventos por animal
CREATE TABLE public.eventos_animal (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at  timestamptz DEFAULT now(),
  animal_id   uuid NOT NULL,
  animal_tipo text NOT NULL CHECK (animal_tipo = ANY (ARRAY['vaca'::text, 'toro'::text])),
  tipo_evento text NOT NULL CHECK (tipo_evento = ANY (ARRAY[
    'vacunacion'::text, 'vitaminacion'::text, 'medicamento'::text,
    'enfermedad'::text, 'celo'::text, 'inseminacion'::text,
    'palpacion'::text, 'confirmacion_prenez'::text, 'parto'::text, 'observacion'::text
  ])),
  fecha       date NOT NULL,
  descripcion text,
  responsable text
);

-- Cooperativa
CREATE TABLE public.fincas_cooperativa (
  id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  nombre      text        NOT NULL,
  precio_litro numeric    NOT NULL DEFAULT 0,
  activa      boolean     NOT NULL DEFAULT true
);

CREATE TABLE public.rutas_cooperativa (
  id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  nombre     text        NOT NULL
);

CREATE TABLE public.rutas_fincas (
  ruta_id  integer NOT NULL REFERENCES public.rutas_cooperativa(id),
  finca_id integer NOT NULL UNIQUE REFERENCES public.fincas_cooperativa(id),
  PRIMARY KEY (ruta_id, finca_id)
);

CREATE TABLE public.recolecciones (
  id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at   timestamptz NOT NULL DEFAULT now(),
  finca_id     integer     NOT NULL REFERENCES public.fincas_cooperativa(id),
  fecha        date        NOT NULL,
  litros       numeric     NOT NULL,
  precio_litro numeric     NOT NULL,
  UNIQUE (finca_id, fecha)
);

-- Roles de usuarios
CREATE TABLE public.roles (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id    uuid        NOT NULL REFERENCES auth.users(id),
  rol        varchar     NOT NULL
);


