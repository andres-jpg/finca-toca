-- Cómo usar:
--   1. Crear un nuevo proyecto en supabase.com (ej: "finca-toca-preview")
--   2. Ir a SQL Editor del nuevo proyecto
--   3. Pegar y ejecutar este script completo
--   4. Crear un usuario en Authentication → Users y añadir su rol (ver al final)
