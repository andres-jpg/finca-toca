SELECT 'animales' AS tabla, count(*) AS huerfanos FROM preview.animales a
  WHERE NOT EXISTS (SELECT 1 FROM preview.tenants t WHERE t.id = a.tenant_id)
UNION ALL
SELECT 'gastos', count(*) FROM preview.gastos g
  WHERE NOT EXISTS (SELECT 1 FROM preview.tenants t WHERE t.id = g.tenant_id)
UNION ALL
SELECT 'roles', count(*) FROM preview.roles r
  WHERE r.tenant_id IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM preview.tenants t WHERE t.id = r.tenant_id);
